#!/usr/bin/env python3
"""Build the Cloudflare Worker that serves acu.caffeinity.com into .build/worker.js.

The pages are embedded in the worker, along with the short routes shu-serve.js serves (/lu, /learn, ...),
the custom 404 page and a robots.txt. wrangler.jsonc points at the output.
    python3 tools/build-site.py
"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / '.build'
OUT.mkdir(exist_ok=True)

pages = {p.name: p.read_text(encoding='utf-8') for p in sorted(ROOT.glob('*.html'))}
favicon = (ROOT / 'favicon.svg').read_text(encoding='utf-8')

# Short routes come from shu-serve.js so the dev server and the live site never drift apart.
js = (ROOT / 'shu-serve.js').read_text(encoding='utf-8')
routes = dict(re.findall(r'"(/[a-z0-9]+)": "([a-z0-9-]+\.html)"', js))
routes['/'] = 'index.html'
routes.update({'/channels': 'channels.html', '/points': 'points.html', '/learn': 'learn.html',
               '/basics': 'basics.html', '/study': 'study.html'})
for name in pages:
    if name != '404.html':
        routes['/' + name] = name  # pages link to each other by file name

worker = f"""// generated by tools/build-site.py; do not edit
const PAGES = {json.dumps(pages, ensure_ascii=False)};
const ROUTES = {json.dumps(routes, ensure_ascii=False)};
const FAVICON = {json.dumps(favicon)};
const HEADERS = {{
  "content-type": "text/html; charset=utf-8",
  "cache-control": "public, max-age=300",
  "x-content-type-options": "nosniff",
  "referrer-policy": "strict-origin-when-cross-origin"
}};
export default {{
  async fetch(req) {{
    const url = new URL(req.url);
    if (req.method !== "GET" && req.method !== "HEAD") return new Response("Method not allowed", {{ status: 405 }});
    const path = url.pathname.replace(/\\/+$/, "") || "/";
    if (path === "/index.html") return Response.redirect(url.origin + "/", 301);
    const file = ROUTES[path] || ROUTES[path.toLowerCase()];
    if (file) return new Response(req.method === "HEAD" ? null : PAGES[file], {{ headers: HEADERS }});
    if (path === "/favicon.svg") return new Response(FAVICON, {{ headers: {{ "content-type": "image/svg+xml", "cache-control": "public, max-age=86400" }} }});
    if (path === "/robots.txt") return new Response("User-agent: *\\nAllow: /\\n", {{ headers: {{ "content-type": "text/plain" }} }});
    return new Response(PAGES["404.html"], {{ status: 404, headers: HEADERS }});
  }}
}};
"""
(OUT / 'worker.js').write_text(worker, encoding='utf-8')
print(f'.build/worker.js: {len(pages)} pages, {len(routes)} routes, {len(worker)//1024} KiB')
